#!/usr/bin/env python3
"""Generate the tracker-variant files consumed by `eval_kitti --variants`.

`dev`  : the exhaustive selection grid of PROTOCOL.md §4 (association x score x
         min_hits; the emission policy E is applied later, in the scorer).
`ablate`: the §5 ablations relative to a chosen (association, score, min_hits) base --
         used for the held-out run only after the dev selection is committed.
"""
from __future__ import annotations

import argparse
import itertools

ASSOC = ["mahalanobis3d", "iou2d", "fused"]
SCORES = [0.25, 0.35, 0.50]
MIN_HITS = [1, 2, 3]


def name(assoc: str, score: float, hits: int) -> str:
    return f"{assoc}_s{score:.2f}_h{hits}"


def dev_grid() -> list[str]:
    lines = []
    for a, s, h in itertools.product(ASSOC, SCORES, MIN_HITS):
        lines.append(f"{name(a, s, h)} assoc={a} score={s} min_hits={h}")
    return lines


def ablations(score: float, hits: int) -> list[str]:
    base = f"score={score} min_hits={hits}"
    return [
        f"F_fused {base} assoc=fused",
        f"A1_no_appearance {base} assoc=fused w3d=0.5 wiou=0.2 wapp=0.0",
        f"A2_no_iou_cost {base} assoc=fused w3d=0.5 wiou=0.0 wapp=0.3",
        f"A3_no_3d_cost {base} assoc=fused w3d=0.0 wiou=0.2 wapp=0.3",
        f"A4_plain_mahalanobis {base} assoc=mahalanobis3d",
        f"A5_plain_iou {base} assoc=iou2d",
        f"A7_greedy {base} assoc=fused hungarian=0",
    ]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--grid", choices=["dev", "ablate"], required=True)
    ap.add_argument("--score", type=float, default=0.25)
    ap.add_argument("--min-hits", type=int, default=3)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    lines = dev_grid() if a.grid == "dev" else ablations(a.score, a.min_hits)
    with open(a.out, "w") as f:
        f.write(f"# generated by scripts/eval/make_variants.py --grid {a.grid}\n")
        f.write("\n".join(lines) + "\n")
    print(f"{len(lines)} variants -> {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
