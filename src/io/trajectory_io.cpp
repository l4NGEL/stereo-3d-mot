void TrajectoryRecorder::record(std::int64_t frame, double timestamp,
                                const std::vector<TrackState>& states) {
    for (const TrackState& s : states) {
        by_id_[s.id].push_back(TrajectoryPoint{frame, timestamp, s});
    }
}

void writeTrajectoriesCsv(const std::string& path, const TrajectoryRecorder& recorder) {
    std::ofstream file(path);
    if (!file)
        throw std::runtime_error("writeTrajectoriesCsv: cannot open '" + path + "'");

    file << "track_id,frame,timestamp,x,y,z,vx,vy,vz,class_id,confirmed\n";
    char line[256];
    for (const auto& [id, points] : recorder.trajectories()) {
        for (const TrajectoryPoint& p : points) {
            std::snprintf(line, sizeof(line), "%d,%lld,%.6f,%.4f,%.4f,%.4f,%.4f,%.4f,%.4f,%d,%d\n",
                          id, static_cast<long long>(p.frame), p.timestamp, p.state.position.x,
                          p.state.position.y, p.state.position.z, p.state.velocity.x,
                          p.state.velocity.y, p.state.velocity.z, p.state.class_id,
                          p.state.confirmed ? 1 : 0);
            file << line;
        }
    }
}

void writeTrajectoriesPly(const std::string& path, const TrajectoryRecorder& recorder) {
    struct Vertex {
        float x, y, z;
        uchar r, g, b;
    };
    std::vector<Vertex> vertices;
    std::vector<std::pair<int, int>> edges;  // vertex indices, both endpoints in `vertices`

    for (const auto& [id, points] : recorder.trajectories()) {
        if (points.size() < 2)
            continue;  // a polyline needs >= 2 points
        const cv::Scalar c = trackColor(id);
        const int base = static_cast<int>(vertices.size());
        for (const TrajectoryPoint& p : points) {
            vertices.push_back(Vertex{p.state.position.x, p.state.position.y, p.state.position.z,
                                      static_cast<uchar>(c[2]), static_cast<uchar>(c[1]),
                                      static_cast<uchar>(c[0])});
        }
        for (std::size_t i = 1; i < points.size(); ++i) {
            edges.emplace_back(base + static_cast<int>(i) - 1, base + static_cast<int>(i));
        }
    }

    std::ofstream file(path);
    if (!file)
        throw std::runtime_error("writeTrajectoriesPly: cannot open '" + path + "'");

    file << "ply\n"
         << "format ascii 1.0\n"
         << "comment generated by stereo_3d_mot (track trajectories)\n"
         << "element vertex " << vertices.size() << "\n"
         << "property float x\nproperty float y\nproperty float z\n"
         << "property uchar red\nproperty uchar green\nproperty uchar blue\n"
         << "element edge " << edges.size() << "\n"
         << "property int vertex1\nproperty int vertex2\n"
         << "end_header\n";

    char line[128];
    for (const Vertex& v : vertices) {
        std::snprintf(line, sizeof(line), "%.4f %.4f %.4f %d %d %d\n", v.x, v.y, v.z,
                      static_cast<int>(v.r), static_cast<int>(v.g), static_cast<int>(v.b));
        file << line;
    }
    for (const auto& [a, b] : edges) {
        std::snprintf(line, sizeof(line), "%d %d\n", a, b);
        file << line;
    }
}

